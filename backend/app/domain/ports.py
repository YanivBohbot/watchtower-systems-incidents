"""Structural interfaces: application services depend on capabilities, not SDKs."""

from pathlib import Path
from typing import Protocol


class Storage(Protocol):
    def put(self, key: str, content: bytes) -> None: ...
    def read(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...
    def local_copy(self, key: str, destination: Path) -> Path: ...


class Embedder(Protocol):
    def embed_documents(self, texts: list[str]) -> list[list[float]]: ...
    def embed_query(self, text: str) -> list[float]: ...


class VectorIndex(Protocol):
    def upsert(self, points: list[dict]) -> None: ...
    def search(self, vector: list[float], limit: int = 5) -> list[dict]: ...
    def delete(self, ids: list[str]) -> None: ...


class FrameSource(Protocol):
    fps: float
    loops: int

    def read(self): ...
    def skip(self, count: int) -> None: ...


class Subscription(Protocol):
    def get(self, timeout: float) -> dict | None: ...
    def close(self) -> None: ...


class LiveHub(Protocol):
    def put_frame(self, camera_id: str, jpeg: bytes) -> None: ...
    def get_frame(self, camera_id: str) -> bytes | None: ...
    def put_status(self, camera_id: str, status: dict) -> None: ...
    def get_status(self, camera_id: str) -> dict | None: ...
    def publish(self, event: dict) -> None: ...
    def subscribe(self) -> Subscription: ...
